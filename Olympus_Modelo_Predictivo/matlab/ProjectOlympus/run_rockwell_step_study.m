function results=run_rockwell_step_study(outputDir)
%RUN_ROCKWELL_STEP_STUDY Reproducible four-rack thermal step study.
% The 41% CPU / 59% other-IT allocation is an explicit scenario assumption,
% not a measured Project Olympus electrical power breakdown. In particular,
% the 80 kW case uses 1 kW/server and is an unvalidated cooling stress case.
if nargin==0
    outputDir=fullfile(fileparts(mfilename('fullpath')),'output');
end
if ~isfolder(outputDir),mkdir(outputDir);end
clear olympus_live_step
model=import_crac_cfd();
dt=5; fan=100; serverFan=72; supply=22;
flowGain=model.model.flow_response.gain_m3_s_per_percent_PWM;
u=struct('dt_s',dt,'Reset',true,'InputSequence',0,...
    'CRAC_PWM_cmd_pct',fan,'CRAC_capacity_fraction',1,...
    'CRAC_supply_temp_C',supply,'MeasuredSupplyTemp_C',supply,...
    'MeasuredCRACFlow_m3_s',flowGain*fan,'Rack_air_volume_m3',.30);
u=set_load(u,0,serverFan);
loadRows=cell(1,4); traceRows=cell(0,1); transferRows=cell(1,2);
for j=1:4
    initialKW=(j-1)*20; finalKW=j*20;
    if j==1
        u.InputSequence=u.InputSequence+1;
        y0=olympus_four_rack_step(u);u.Reset=false;
    else
        y0=y;
    end
    u=set_load(u,finalKW,serverFan);
    [y,trace,settled]=run_plateau(u,y0,7200,dt);
    u.InputSequence=u.InputSequence+numel(trace);
    [tauIn,tauOut]=response_times(trace,y0,y);
    loadRows{j}=struct('Step',sprintf('%g_to_%g_kW',initialKW,finalKW),...
        'Initial_kW',initialKW,'Final_kW',finalKW,...
        'CPU_W_per_server',finalKW*1000/80*.41,...
        'OtherIT_W_per_server',finalKW*1000/80*.59,...
        'Initial_rack_inlet_C',y0.Rack_inlet_C,'Final_rack_inlet_C',y.Rack_inlet_C,...
        'Delta_rack_inlet_C',y.Rack_inlet_C-y0.Rack_inlet_C,...
        'Rack_inlet_t63_s',tauIn,...
        'Initial_rack_outlet_C',y0.Rack_outlet_C,'Final_rack_outlet_C',y.Rack_outlet_C,...
        'Delta_rack_outlet_C',y.Rack_outlet_C-y0.Rack_outlet_C,...
        'Rack_outlet_t63_s',tauOut,...
        'Plenum_tracer_t50_s_at_100pct_CFD',model.model.air_transport.t50_s,...
        'Plenum_tracer_t63_s_at_100pct_CFD',model.model.air_transport.t63_s,...
        'Step_duration_s',numel(trace)*dt,'Settled',settled,...
        'Thermal_alarm_at_final',y.ThermalAlarm);
    for k=1:numel(trace)
        traceRows{end+1}=struct('Experiment',loadRows{j}.Step,...
            'Time_since_step_s',k*dt,'Total_IT_kW',finalKW,...
            'CRAC_PWM_pct',fan,'Supply_setpoint_C',supply,...
            'Rack_inlet_C',trace(k).Rack_inlet_C,...
            'Rack_outlet_C',trace(k).Rack_outlet_C,...
            'Max_CPU_die_est_C',max([trace(k).CPU1_die_est_C trace(k).CPU2_die_est_C]),...
            'Thermal_alarm',trace(k).ThermalAlarm); %#ok<AGROW>
    end
end
% Each transfer experiment starts from a separately equilibrated 40 kW case.
for experiment=1:2
    clear olympus_live_step
    base=u;base.Reset=true;base.InputSequence=1;base.CRAC_PWM_cmd_pct=80;
    base.MeasuredCRACFlow_m3_s=flowGain*80;
    base.CRAC_supply_temp_C=22;base.MeasuredSupplyTemp_C=22;
    base=set_load(base,40,serverFan);
    start=olympus_four_rack_step(base);base.Reset=false;
    [start,~,baseSettled]=run_plateau(base,start,7200,dt);
    assert(baseSettled,'The 40 kW transfer baseline did not settle.');
    if experiment==1
        test=base;test.CRAC_PWM_cmd_pct=85;
        test.MeasuredCRACFlow_m3_s=flowGain*85;
        name='CRAC_fan_80_to_85_PWM_pct'; inputDelta=5; units='C_per_PWM_percentage_point';
    else
        test=base;test.CRAC_supply_temp_C=24;test.MeasuredSupplyTemp_C=24;
        name='Supply_air_22_to_24_C'; inputDelta=2; units='C_per_supply_C';
    end
    [finish,trace,settled]=run_plateau(test,start,7200,dt);
    [tauIn,tauOut]=response_times(trace,start,finish);
    transferRows{experiment}=struct('Experiment',name,...
        'Input_change',inputDelta,'Gain_units',units,...
        'Initial_rack_inlet_C',start.Rack_inlet_C,...
        'Final_rack_inlet_C',finish.Rack_inlet_C,...
        'Rack_inlet_gain',(finish.Rack_inlet_C-start.Rack_inlet_C)/inputDelta,...
        'Rack_inlet_t63_s',tauIn,...
        'Initial_rack_outlet_C',start.Rack_outlet_C,...
        'Final_rack_outlet_C',finish.Rack_outlet_C,...
        'Rack_outlet_gain',(finish.Rack_outlet_C-start.Rack_outlet_C)/inputDelta,...
        'Rack_outlet_t63_s',tauOut,'Step_duration_s',numel(trace)*dt,...
        'Settled',settled,'Thermal_alarm_at_final',finish.ThermalAlarm);
    for k=1:numel(trace)
        traceRows{end+1}=struct('Experiment',name,...
            'Time_since_step_s',k*dt,'Total_IT_kW',40,...
            'CRAC_PWM_pct',test.CRAC_PWM_cmd_pct,...
            'Supply_setpoint_C',test.CRAC_supply_temp_C,...
            'Rack_inlet_C',trace(k).Rack_inlet_C,...
            'Rack_outlet_C',trace(k).Rack_outlet_C,...
            'Max_CPU_die_est_C',max([trace(k).CPU1_die_est_C trace(k).CPU2_die_est_C]),...
            'Thermal_alarm',trace(k).ThermalAlarm); %#ok<AGROW>
    end
end
results=struct('load_steps',struct2table([loadRows{:}]),'transfer',struct2table([transferRows{:}]),...
    'time_series',struct2table([traceRows{:}]));
writetable(results.load_steps,fullfile(outputDir,'rockwell_load_steps_summary.csv'));
writetable(results.transfer,fullfile(outputDir,'rockwell_transfer_summary.csv'));
writetable(results.time_series,fullfile(outputDir,'rockwell_step_timeseries.csv'));
disp(results.load_steps);disp(results.transfer);
end

function u=set_load(u,totalKW,serverFan)
% 80 identical servers, four racks. Each endpoint respects 205 W per CPU.
perServer=totalKW*1000/80;
for rack=1:4
    u.RackLoads(rack)=struct('CPU1_W',perServer*.41/2,...
        'CPU2_W',perServer*.41/2,'OtherIT_W_per_server',perServer*.59,...
        'ServerFan_pct',serverFan);
end
assert(abs(80*(u.RackLoads(1).CPU1_W+u.RackLoads(1).CPU2_W+...
    u.RackLoads(1).OtherIT_W_per_server)-totalKW*1000)<1e-8);
end

function [last,trace,settled]=run_plateau(u,start,maxSeconds,dt)
trace=repmat(start,1,maxSeconds/dt);
last=start;settled=false;
for k=1:numel(trace)
    u.InputSequence=u.InputSequence+1;
    last=olympus_four_rack_step(u);trace(k)=last;
    assert(last.DataValid && abs(last.Energy_balance_residual_J)<1e-4,...
        'Nonfinite state or energy balance failure.');
    if k>=240 && mod(k,60)==0
        prior=trace(k-60);
        if abs(last.Rack_inlet_C-prior.Rack_inlet_C)<.01 && ...
           abs(last.Rack_outlet_C-prior.Rack_outlet_C)<.01 && ...
           abs(last.CPU1_die_est_C-prior.CPU1_die_est_C)<.02
            settled=true;trace=trace(1:k);return
        end
    end
end
end

function [tin,tout]=response_times(trace,start,finish)
tin=crossing_time([trace.Rack_inlet_C],start.Rack_inlet_C,finish.Rack_inlet_C,5);
tout=crossing_time([trace.Rack_outlet_C],start.Rack_outlet_C,finish.Rack_outlet_C,5);
end

function t=crossing_time(values,initial,final,dt)
target=initial+(1-exp(-1))*(final-initial);
if final>=initial,idx=find(values>=target,1);else,idx=find(values<=target,1);end
if isempty(idx),t=NaN;return;end
if idx==1,t=dt;return;end
fraction=(target-values(idx-1))/(values(idx)-values(idx-1));
t=(idx-1+fraction)*dt;
end
